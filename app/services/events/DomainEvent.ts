// ─── Base envelope ────────────────────────────────────────────

export interface DomainEventEnvelope {
  /** Generated UUIDv7 ID */
  id: string;
  /** Versioned event type name, e.g. `"ProductCreated.v1"` */
  type: string;
  /**
   * CloudEvents spec version. Always `"1.0"`.
   * @see https://cloudevents.io
   */
  specversion: "1.0";
  /**
   * URI pointing to the JSON Schema that describes the `data` payload for this event type.
   * Follows the CloudEvents `dataschema` attribute convention.
   * Example: `https://orr-sample.vercel.app/schemas/ProductCreated.v1.json`
   */
  dataschema?: string;
  /**
   * Origin of the event.
   * - `"peaky.client"` — written by the browser client before sync
   * - `"peaky.sync"`   — received from the server during a pull sync
   * - `"peaky.system"` — generated by automated processes (e.g., scheduled jobs)
   */
  source: "peaky.client" | "peaky.sync" | "peaky.system";

  // ─── Extension attributes (top-level per CloudEvents spec) ──

  /** ID of the user or system that triggered the event */
  actorId: string;
  actorType: "user" | "integration" | "system";

  /** Kind and stable ID of the subject entity */
  entityType: string;
  entityId: string;

  /**
   * Cross-entity correlation key — links events from different entity types
   * back to the same review (e.g., `review_answer` events reference their
   * parent `review` here).
   */
  reviewId?: string;
  /** Browser session identifier */
  clientId?: string;

  // ─── CloudEvents core ───────────────────────────────────────

  /** ISO 8601 timestamp (CloudEvents `time` attribute) */
  time: string;

  // Typed payload
  data: Record<string, unknown>;
}

