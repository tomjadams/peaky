/**
 * Domain event type hierarchy (CloudEvents v1.0.2 aligned).
 *
 * All domain operations produce a typed event. Events are:
 * - Source-attributed (`peaky.client` | `peaky.sync` | `peaky.system`)
 * - Cross-domain (entity_type + entity_id, not just review_id)
 * - Version-suffixed (e.g. `.v1`) — the `type` string carries the version
 *
 * CloudEvents core attributes: id, type, specversion, source, time, dataschema.
 * Extension attributes (top-level per spec): actorId, actorType, entityType,
 * entityId, reviewId, clientId.
 *
 * Discriminated union pattern:
 *   Narrowing on `event.type` gives you a fully typed `event.data` payload.
 *   Example:
 *     if (event.type === "ProductCreated.v1") {
 *       // event.data is ProductCreated["data"] — name, teamIds, componentIds
 *     }
 *
 * @see shared/db/schema/event.ts — persisted as events table
 * @see app/services/events/schemas/index.ts — JSON Schema catalog
 */

