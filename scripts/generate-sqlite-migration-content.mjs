import { readdir, readFile, writeFile } from "node:fs/promises";

const migrationsDir = new URL(
  "../shared/db/migrations/sqlite/",
  import.meta.url
);
const outputPath = new URL(
  "../shared/db/migrations/sqlite-content.ts",
  import.meta.url
);

function toConstName(fileName) {
  const stem = fileName.replace(/\.sql$/u, "");
  const camel = stem
    .split(/[_-]+/u)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

  return `migration${camel}Sql`;
}

function escapeTemplateLiteral(source) {
  return source.replaceAll("`", "\\`").replaceAll("${", "\\${");
}

async function main() {
  const fileNames = (await readdir(migrationsDir))
    .filter((fileName) => fileName.endsWith(".sql"))
    .toSorted();

  const contents = await Promise.all(
    fileNames.map(async (fileName) => {
      const sql = await readFile(new URL(fileName, migrationsDir), "utf8");
      return {
        fileName,
        constName: toConstName(fileName),
        sql: escapeTemplateLiteral(sql),
      };
    })
  );

  const lines = [
    "// GENERATED FILE - DO NOT EDIT.",
    "// Generated by scripts/generate-sqlite-migration-content.mjs from shared/db/migrations/sqlite/*.sql",
    "/* eslint-disable max-lines -- generated file, content length is determined by migration count */",
    'import type { SQLiteMigration } from "./index";',
    "",
  ];

  for (const migration of contents) {
    lines.push(
      `const ${migration.constName} = String.raw\`${migration.sql}\`;`,
      ""
    );
  }

  lines.push(
    "const SQLITE_MIGRATION_SQL_BY_FILE_NAME: Record<string, string> = {"
  );

  for (const migration of contents) {
    lines.push(`  "${migration.fileName}": ${migration.constName},`);
  }

  lines.push(
    "};",
    "",
    "export function getSQLiteMigrationSql(migration: SQLiteMigration): string {",
    "  const sql = SQLITE_MIGRATION_SQL_BY_FILE_NAME[migration.fileName];",
    "",
    "  if (!sql) {",
    "    throw new Error(`Missing SQL content for migration ${migration.fileName}`);",
    "  }",
    "",
    "  return sql;",
    "}",
    ""
  );

  await writeFile(outputPath, lines.join("\n"), "utf8");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
